# =========================================================
# GET COLORS
# =========================================================

def get_colors():

    theme_name = get_setting(
        "theme",
        "OCEAN"
    )

    appearance = get_setting(
        "appearance",
        "DARK"
    )


    if theme_name not in THEMES:

        theme_name = "OCEAN"


    theme = THEMES[theme_name]


    # =====================================================
    # DARK MODE
    # =====================================================

    if appearance != "LIGHT":

        return {
            "bg": theme["bg"],
            "card": theme["card"],
            "card2": theme["card2"],
            "text": theme["text"],
            "muted": theme["muted"],
            "accent": theme["accent"],
            "success": theme["success"],
            "danger": theme["danger"],
        }


    # =====================================================
    # LIGHT MODE
    # =====================================================

    return {
        "bg": theme["light_bg"],
        "card": theme["light_card"],
        "card2": theme["light_card2"],
        "text": theme["light_text"],
        "muted": theme["light_muted"],
        "accent": theme["light_accent"],
        "success": theme["success"],
        "danger": theme["danger"],
    }


# =========================================================
# APPLY WINDOW
# =========================================================

def apply_window():

    colors = get_colors()

    Window.clearcolor = colors["bg"]